    # Membuat variabel target biner 'good_bad'
    # 1 = Kredit Buruk (Bad Credit)
    # 0 = Kredit Baik (Good Credit)
    bad_indicators = ['Charged Off', 'Default', 'Late (31-120 days)', 'Late (16-30 days)']

