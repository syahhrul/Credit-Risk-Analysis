"""## 3. PEMAHAMAN DATA & REKAYASA FITUR TARGET"""

if not data.empty:
    print("Mulai: Pemahaman Data dan Rekayasa Fitur Target...")

    # Menampilkan 5 baris pertama
    print("Data Head:")
    print(data.head())
    print("\n")

    # Menampilkan informasi dasar DataFrame
    print("Informasi Data (Awal):")
